#!/usr/bin/env node
/**
 * v0.1 vertical-slice E2E (plan todo 22) вЂ” Playwright _electron.
 *
 * Journey: clean cache в†’ launch built app в†’ type TS program using lodash в†’
 * run в†’ inspect Map result в†’ select sum() в†’ cold-start install d8-debug в†’
 * Analyze Bytecode в†’ normalized rows + raw non-empty. Green twice in a row
 * proves recovery; first run logs the cold-start duration (--warm skips it).
 *
 * Run:  pnpm build && node scripts/e2e-vertical-slice.mjs [--warm]
 */
import { _electron as electron } from 'playwright';
import { mkdtemp, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const WARM = process.argv.includes('--warm');
const log = (m) => console.log(`[e2e] ${m}`);
const timings = {};

// Persistent cache dir: cold run wipes it (exercising the download path),
// warm run reuses it (proving recovery/reuse green-on-green).
const cacheDir = join(tmpdir(), 'rh-e2e-cache');
if (!WARM) await rm(cacheDir, { recursive: true, force: true });
process.env['RH_CACHE_ROOT'] = cacheDir;

const home = await mkdtemp(join(tmpdir(), 'rh-e2e-home-'));
// Chromium (crashpad/GPU cache) expects these under USERPROFILE/APPDATA.
await mkdir(join(home, 'AppData', 'Local'), { recursive: true });
await mkdir(join(home, 'AppData', 'Roaming'), { recursive: true });

process.env['USERPROFILE'] = home;
process.env['APPDATA'] = join(home, 'AppData', 'Roaming');

// Environment prep: lodash available in the default workspace (mirrors the
// PackagesPanel flow; UI-driven install is covered by t13 evidence).
const wsDir = join(home, 'RuntimeHell', 'workspaces', 'default');
await mkdir(wsDir, { recursive: true });
await writeFile(
  join(wsDir, 'package.json'),
  JSON.stringify({ name: 'playground', private: true, type: 'commonjs', dependencies: {} }, null, 2),
  'utf8'
);
log('npm install lodash into fresh workspaceвЂ¦');
{
  const { execFileSync } = await import('node:child_process');
  execFileSync('cmd.exe', ['/d', '/s', '/c', 'npm i --no-audit --no-fund --ignore-scripts lodash'], {
    cwd: wsDir,
    stdio: 'ignore',
    shell: false
  });
}

log('launching electron (built app)вЂ¦');
const app = await electron.launch({ args: ['.'], env: { ...process.env }, timeout: 60_000 });
const win = await app.firstWindow();
win.on('console', (msg) => {
  if (msg.text().startsWith('[boot]')) log(msg.text());
});

await win.waitForFunction(() => window.__rh_editor !== undefined, null, { timeout: 30_000 });
log('editor ready');

// 1. Type the TS program (lodash + Map + sum).
const PROGRAM = [
  "import _ from 'lodash';",
  'interface User { id: number; name: string }',
  "const users: User[] = [{ id: 1, name: 'Alex' }, { id: 2, name: 'Sam' }];",
  'const chunked = _.chunk(users, 1);',
  'const map = new Map<number, string>();',
  'map.set(1, "one");',
  'map.set(2, "two");',
  'chunked.length;',
  'map.size;',
  'function sum(a: number, b: number): number {',
  '  return a + b;',
  '}',
  'sum(40, 2);'
].join('\n');
await win.evaluate(([v]) => window.__rh_editor.setValue(v), [PROGRAM]);
log('program typed');

// 2. Run via Ctrl+Enter; wait for the exit badge.
await win.locator('.monaco-editor').click();
await win.keyboard.press('Control+Enter');
try {
  await win.waitForFunction(() => document.body.innerText.includes('exit '), null, { timeout: 30_000 });
} catch {
  const snap = await win.evaluate(() => document.body.innerText.slice(0, 800));
  log(`TIMEOUT SNAPSHOT: ${snap.replace(/\n/g, ' | ')}`);
  throw new Error('run did not complete');
}
log('run completed');

// 3. Inspector tab renders Map rows.
await win.getByRole('button', { name: 'inspector', exact: true }).click();
try {
  await win.waitForFunction(() => document.body.innerText.includes('Map(2)'), null, { timeout: 15_000 });
} catch {
  const snap = await win.evaluate(() => document.body.innerText.slice(0, 1200));
  log(`INSPECTOR SNAPSHOT: ${snap.replace(/\n/g, ' | ')}`);
  throw new Error('Map(2) not rendered');
}
log('inspector shows Map(2)');

// 4. Select sum() and analyze bytecode on d8-debug (cold-start download).
const t0 = Date.now();
await win.evaluate(() => window.__rh_editor.setSelection(10, 1, 12, 2));
if (!WARM) {
  log('cold-start: installing d8-debug via managed downloaderвЂ¦');
  const install = await win.evaluate(() => window.api.installEngine('d8-debug'));
  assert.equal(install.ok, true);
  log(`d8-debug ${install.entry.version} installed`);
}
await win.getByRole('button', { name: 'analysis', exact: true }).click();
await win.getByRole('button', { name: 'Bytecode', exact: true }).click();
try {
  await win.waitForFunction(
    () => document.body.innerText.includes('generated bytecode') || document.body.innerText.includes('unsupported'),
    null,
    { timeout: 120_000 }
  );
} catch {
  const snap = await win.evaluate(() => {
    const dbg = window.__rh_debug;
    return JSON.stringify({ tab: dbg?.drawerTab?.(), analysis: dbg?.analysis?.(), text: document.body.innerText.slice(0, 700) });
  });
  log(`ANALYSIS SNAPSHOT: ${snap.replace(/\n/g, ' | ')}`);
  throw new Error('bytecode analysis did not produce output');
}
timings.analysisMs = Date.now() - t0;
if (!WARM) timings.coldStartAnalysisMs = timings.analysisMs;
log(`analysis done in ${timings.analysisMs}ms`);

// 5. Normalized table contains sum; raw tab non-empty.
await win.getByRole('button', { name: 'normalized', exact: true }).click();
await win.waitForFunction(() => document.body.innerText.includes('best-effort normalization'), null, { timeout: 15_000 });
const bodyText = await win.evaluate(() => document.body.innerText);
assert.match(bodyText, /sum/);
await win.getByRole('button', { name: 'raw', exact: true }).click();
const rawText = await win.evaluate(() => {
  const pre = [...document.querySelectorAll('pre')].at(-1);
  return pre?.textContent ?? '';
});
assert.ok(rawText.length > 50, 'raw output must be non-empty');

console.log(JSON.stringify({ ok: true, warm: WARM, timings }, null, 2));
await app.close();
await rm(home, { recursive: true, force: true });
log('PASS');
