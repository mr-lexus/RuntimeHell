function writeManifest(entries: Record<string, unknown>[]): Promise<void> {
  return import('node:fs/promises').then((fs) =>
    fs.writeFile(
      join(dir, 'manifest.json'),
      JSON.stringify({
        schemaVersion: 1,
        entries: entries.map((e) => ({
          license: 'BSD',
          source: 'official-canary',
          customBuildRequired: false,
          ...e
        }))
      }),
      'utf8'
    )
  );
}

describe('EngineRegistry', () => {
  it('describes installed engines with cached capabilities keyed by hash', async () => {
    process.env['RH_CACHE_ROOT'] = dir;
    await writeManifest([
      {
        kind: 'engine',
        id: 'd8-debug',
        platform: 'win64',
        arch: 'x64',
        version: '13.2.152.16',
        url: 'https://storage.googleapis.com/chromium-v8/official/canary/x.zip',
        sha256: 'a'.repeat(64),
        installedPath: dir
      }
    ]);
    // Point ENGINE_BINARY_NAME resolution at our fake binary file.
    await writeFile(join(dir, executableName('d8')), 'binary:d8-dbg', 'utf8');

    let executions = 0;
    const countingExecutor: ExecuteBinary = async (exe, args) => {
      executions += 1;
      return debugD8(exe, args);
    };
    const registry = new EngineRegistry({ execute: countingExecutor, hash: async () => 'fixed-hash' });

    const first = await registry.describe('d8-debug');
    expect(first.version).toBe('13.2.152.16');
    expect((first.capabilities as EngineCapabilities).astDump).toBe(true);

    const second = await registry.describe('d8-debug');
    expect(second.capabilities).toEqual(first.capabilities);
    expect(executions).toBe(9); // one full suite (liveness + 8 probes), then cache hit

    delete process.env['RH_CACHE_ROOT'];
  });

  it('reports missing engines with a reason and null capabilities', async () => {
    process.env['RH_CACHE_ROOT'] = join(dir, 'empty-cache');
    await import('node:fs/promises').then((fs) => fs.mkdir(join(dir, 'empty-cache'), { recursive: true }));
    const registry = new EngineRegistry({ execute: masqueradingNode });
    const desc = await registry.describe('spidermonkey');
    expect(desc.capabilities).toBeNull();
    expect(desc.reason).toContain('not installed');
    delete process.env['RH_CACHE_ROOT'];
  });
});
